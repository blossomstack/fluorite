use fluorite_codegen::code_gen::ir::{IRUnion, IRUnionVariant};

#[test]
fn generates_a_union_as_a_sealed_interface_wrapper() {
    let user = IRStruct {
        name: "User".to_string(),
        doc: None,
        deny_unknown_fields: false,
        fields: vec![field(
            "id",
            IRFieldType::Primitive(IRPrimitive::String),
            false,
            None,
        )],
    };
    let u = IRUnion {
        name: "UserEvent".to_string(),
        tag_field: "type".to_string(),
        content_field: "value".to_string(),
        doc: None,
        variants: vec![
            IRUnionVariant::Newtype {
                name: "Created".to_string(),
                ty: IRFieldType::Custom(IRTypeRef::new("demo", "User")),
                doc: None,
            },
            IRUnionVariant::Unit {
                name: "Deleted".to_string(),
                doc: None,
            },
            IRUnionVariant::Newtype {
                name: "Renamed".to_string(),
                ty: IRFieldType::Primitive(IRPrimitive::String),
                doc: None,
            },
        ],
    };
    let schema = schema_of("demo", vec![IRType::Struct(user), IRType::Union(u)]);
    let (generator, fs) = generator(GoOptions::new("out".to_string()).with_package_name("demo"));
    generator.generate_from_schema(&schema).unwrap();

    let content = fs.get_string("out/user_event.go").unwrap();

    assert!(
        content.contains("import (\n\t\"encoding/json\"\n\t\"fmt\"\n)\n"),
        "{content}"
    );
    assert!(
        content.contains("type UserEventVariant interface {\n\tisUserEventVariant()\n}\n"),
        "{content}"
    );
    assert!(
        content.contains("type UserEventCreated struct {\n\tValue User\n}\n"),
        "{content}"
    );
    assert!(
        content.contains("func (UserEventCreated) isUserEventVariant() {}\n"),
        "{content}"
    );
    assert!(
        content.contains("type UserEventDeleted struct{}\n"),
        "{content}"
    );
    assert!(
        content.contains("type UserEventRenamed struct {\n\tValue string\n}\n"),
        "{content}"
    );
    assert!(
        content.contains("type UserEvent struct {\n\tVariant UserEventVariant\n}\n"),
        "{content}"
    );
    assert!(
        content.contains("\tcase UserEventCreated:\n\t\treturn json.Marshal(struct {\n\t\t\tType  string `json:\"type\"`\n\t\t\tValue User   `json:\"value\"`\n\t\t}{\"Created\", v.Value})\n"),
        "{content}"
    );
    assert!(
        content.contains("\tcase UserEventDeleted:\n\t\treturn json.Marshal(struct {\n\t\t\tType string `json:\"type\"`\n\t\t}{\"Deleted\"})\n"),
        "{content}"
    );
    assert!(
        content.contains(
            "\tcase nil:\n\t\treturn nil, fmt.Errorf(\"fluorite: UserEvent has no variant set\")\n"
        ),
        "{content}"
    );
    assert!(
        content.contains(
            "\t\tType  string          `json:\"type\"`\n\t\tValue json.RawMessage `json:\"value\"`\n"
        ),
        "{content}"
    );
    assert!(
        content.contains("\t\tu.Variant = UserEventDeleted{}\n"),
        "{content}"
    );
    assert!(
        content.contains(
            "return fmt.Errorf(\"fluorite: unknown UserEvent variant tag %q\", envelope.Type)\n"
        ),
        "{content}"
    );
}

