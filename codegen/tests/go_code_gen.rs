#[test]
fn multi_line_docs_survive_on_types_fields_and_variants() {
    let s = IRStruct {
        name: "Doc".to_string(),
        doc: Some("Summary line.\n\nDetail line.".to_string()),
        deny_unknown_fields: false,
        fields: vec![field(
            "id",
            IRFieldType::Primitive(IRPrimitive::String),
            false,
            Some("First.\nSecond."),
        )],
    };
    let e = IREnum {
        name: "Kind".to_string(),
        doc: None,
        variants: vec![IREnumVariant {
            name: "One".to_string(),
            doc: Some("The only one.".to_string()),
        }],
    };
    let u = IRUnion {
        name: "Evt".to_string(),
        tag_field: "type".to_string(),
        content_field: "value".to_string(),
        doc: Some("An event.".to_string()),
        variants: vec![IRUnionVariant::Unit {
            name: "Gone".to_string(),
            doc: Some("It went away.".to_string()),
        }],
    };
    let schema = schema_of(
        "demo",
        vec![IRType::Struct(s), IRType::Enum(e), IRType::Union(u)],
    );
    let (generator, fs) = generator(GoOptions::new("out".to_string()).with_package_name("demo"));
    generator.generate_from_schema(&schema).unwrap();

    // A blank doc line becomes a bare `//`, never `// ` with trailing space.
    let doc_go = fs.get_string("out/doc.go").unwrap();
    assert!(
        doc_go.contains("// Summary line.\n//\n// Detail line.\ntype Doc struct {\n"),
        "{doc_go}"
    );
    assert!(
        doc_go.contains("\t// First.\n\t// Second.\n\tID string `json:\"id\"`\n"),
        "{doc_go}"
    );

    let kind_go = fs.get_string("out/kind.go").unwrap();
    assert!(
        kind_go.contains("const (\n\t// The only one.\n\tKindOne Kind = \"One\"\n)\n"),
        "{kind_go}"
    );

    let evt_go = fs.get_string("out/evt.go").unwrap();
    assert!(
        evt_go.contains("// It went away.\ntype EvtGone struct{}\n"),
        "{evt_go}"
    );
    assert!(
        evt_go.contains("// An event.\n// Evt is an adjacently tagged union"),
        "{evt_go}"
    );
}
